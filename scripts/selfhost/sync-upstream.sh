#!/usr/bin/env bash
set -euo pipefail

# Import a stable public Multica release into the vendor branch, apply only the
# upstream delta to the localized product, validate it, and optionally advance
# main. Conflicts are intentionally left on a reviewable sync branch so an
# agent can resolve them without putting main in a half-merged state.

ROOT_DIR="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [ -z "$ROOT_DIR" ]; then
  echo "error: run this script from a Multica Git checkout" >&2
  exit 2
fi
cd "$ROOT_DIR"

PUBLIC_URL="${MULTICA_UPSTREAM_GIT_URL:-https://github.com/multica-ai/multica.git}"
PRIVATE_REMOTE="${MULTICA_PRIVATE_REMOTE:-origin}"
BASE_BRANCH="${MULTICA_BASE_BRANCH:-main}"
COMPAT_BRANCH="${MULTICA_COMPAT_BRANCH:-mikeux}"
VENDOR_BRANCH="${MULTICA_VENDOR_BRANCH:-vendor/upstream}"
CHECK_CMD="${MULTICA_SYNC_CHECK_CMD:-pnpm --filter @multica/web exec vitest run features/landing/utils/github-release.test.ts && pnpm --filter @multica/web typecheck && (cd server && go test ./pkg/agent -run 'TestDsh|TestDiscoverDsh' -count=1)}"
COMMITTER_NAME="${MULTICA_SYNC_COMMITTER_NAME:-Multica Upstream Sync Bot}"
COMMITTER_EMAIL="${MULTICA_SYNC_COMMITTER_EMAIL:-multica-sync@localhost}"
GIT_IDENTITY=(-c "user.name=$COMMITTER_NAME" -c "user.email=$COMMITTER_EMAIL")
PUSH=0
MERGE_MAIN=0
MODE=run
REQUESTED_TAG=""

usage() {
  cat <<'EOF'
Usage: scripts/selfhost/sync-upstream.sh [options]

Options:
  --check-only       Report whether a newer stable public release exists.
  --tag vX.Y.Z       Import this stable release instead of detecting latest.
  --merge-main       Fast-forward main after a conflict-free validated import.
  --push             Push created branches and tags to the private remote.
  --resume           Continue after an agent has resolved conflicts.
  --public-url URL   Override the public Multica Git URL.
  --remote NAME      Override the private remote (default: origin).
  -h, --help         Show this help.

Environment:
  MULTICA_SYNC_CHECK_CMD   Validation command run before integration.
  MULTICA_SYNC_COMMITTER_NAME  Commit/tag identity name for automated syncs.
  MULTICA_SYNC_COMMITTER_EMAIL Commit/tag identity email for automated syncs.
  MULTICA_UPSTREAM_GIT_URL Public Git remote (default: GitHub Multica).
  MULTICA_BASE_BRANCH     Localized branch (default: main).
  MULTICA_COMPAT_BRANCH   Compatibility branch advanced with main (default: mikeux).

Safe default: create a local sync branch only. For unattended, fully automatic
operation use --merge-main --push. A conflict never advances main.
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --check-only) MODE=check ;;
    --tag) shift; REQUESTED_TAG="${1:-}" ;;
    --merge-main) MERGE_MAIN=1 ;;
    --push) PUSH=1 ;;
    --resume) MODE=resume ;;
    --public-url) shift; PUBLIC_URL="${1:-}" ;;
    --remote) shift; PRIVATE_REMOTE="${1:-}" ;;
    -h|--help) usage; exit 0 ;;
    *) echo "error: unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

GIT_DIR="$(git rev-parse --git-dir)"
case "$GIT_DIR" in /*) ;; *) GIT_DIR="$ROOT_DIR/$GIT_DIR" ;; esac
LOCK_DIR="$GIT_DIR/multica-upstream-sync.lock"
STATE_FILE="$GIT_DIR/multica-upstream-sync.state"
SUMMARY_FILE="$GIT_DIR/multica-upstream-sync-summary.json"

if ! mkdir "$LOCK_DIR" 2>/dev/null; then
  echo "error: another Multica upstream sync is running ($LOCK_DIR)" >&2
  exit 3
fi
trap 'rmdir "$LOCK_DIR" 2>/dev/null || true' EXIT

is_stable_tag() {
  [[ "$1" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]
}

version_key() {
  local tag=${1#vendor/}; tag=${tag#v}
  local major minor patch
  IFS=. read -r major minor patch <<<"$tag"
  printf '%012d.%012d.%012d' \
    "$((10#$major))" "$((10#$minor))" "$((10#$patch))"
}

latest_stable_from_lines() {
  local line best="" best_key="" key
  while IFS= read -r line; do
    is_stable_tag "$line" || continue
    key="$(version_key "$line")"
    if [ -z "$best_key" ] || [[ "$key" > "$best_key" ]]; then
      best=$line; best_key=$key
    fi
  done
  printf '%s' "$best"
}

integrated_vendor_tag() {
  local snapshot tag marker
  marker="$(git log "$BASE_BRANCH" --format=%B | \
    sed -n '/^Vendor snapshot:/p' | head -n 1)"
  if [ -n "$marker" ]; then
    snapshot="${marker#Vendor snapshot: }"
    [[ "$snapshot" =~ ^[0-9a-f]{7,40}$ ]] || return 1
    snapshot="$(git rev-parse --verify "$snapshot^{commit}" 2>/dev/null)" || return 1
    while IFS= read -r tag; do
      [ "$(git rev-parse "$tag^{commit}" 2>/dev/null || true)" = "$snapshot" ] && {
        printf '%s' "$tag"
        return
      }
    done < <(git tag --list 'vendor/v*')
    return 1
  fi

  # Repositories created before integration trailers existed have no precise
  # marker. Preserve the old behavior only for that legacy case.
  [ -n "$latest_vendor" ] && printf 'vendor/%s' "$latest_vendor"
}

write_summary() {
  local status=$1 tag=${2:-} branch=${3:-} message=${4:-}
  # Values are refs and fixed messages generated by this script; strip the only
  # characters that could make the small JSON record invalid.
  message=${message//\\/\\\\}; message=${message//\"/\\\"}
  printf '{"status":"%s","upstreamTag":"%s","branch":"%s","message":"%s"}\n' \
    "$status" "$tag" "$branch" "$message" | tee "$SUMMARY_FILE"
}

require_clean_tree() {
  if [ -n "$(git status --porcelain)" ]; then
    echo "error: working tree must be clean" >&2
    exit 4
  fi
}

verify_local_boundary() {
  local release_file=apps/web/features/landing/utils/github-release.ts
  local builder=scripts/selfhost/build-desktop-macos.sh
  [ -f "$release_file" ] && [ -f "$builder" ] || {
    echo "error: localized Forgejo/macOS integration files are missing" >&2
    return 1
  }
  grep -Fq 'DESKTOP_RELEASES_SOURCE' "$release_file"
  grep -Fq 'FORGEJO_BASE_URL' "$release_file"
  grep -Fq 'FORGEJO_TOKEN' "$release_file"
  grep -Eq -- '-mikeux(\\)?\.' "$builder"
  # Desktop packaging must stay limited to plain vX.Y.Z product releases (plus
  # the historical -mikeux.N tags). A localized vX.Y.Z.N release is server-only:
  # its four-component version is not valid semver, so electron-updater would
  # refuse to start in the built app and an installed client could never take
  # the next upstream release.
  grep -Fq '^v[0-9]+\.[0-9]+\.[0-9]+(-mikeux\.[0-9]+)?$' "$builder"
  test -f scripts/selfhost/dsh-agent.json
  test -f server/pkg/agent/dsh.go
  test -f server/pkg/agent/dsh_test.go
}

run_checks() {
  verify_local_boundary
  if [ -n "$CHECK_CMD" ]; then
    echo "==> Running validation: $CHECK_CMD"
    /bin/bash -lc "$CHECK_CMD"
  fi
}

save_state() {
  cat >"$STATE_FILE" <<EOF
SYNC_TAG=$SYNC_TAG
OLD_VENDOR_TAG=$OLD_VENDOR_TAG
SYNC_BRANCH=$SYNC_BRANCH
BASE_SHA=$BASE_SHA
VENDOR_COMMIT=$VENDOR_COMMIT
EOF
}

load_state() {
  [ -f "$STATE_FILE" ] || {
    echo "error: no interrupted sync state found" >&2
    exit 5
  }
  # State values are generated refs/SHAs and validated immediately below.
  # shellcheck disable=SC1090
  . "$STATE_FILE"
  is_stable_tag "$SYNC_TAG" || { echo "error: invalid sync state tag" >&2; exit 5; }
  [[ "$SYNC_BRANCH" == "sync/upstream-$SYNC_TAG" ]] || { echo "error: invalid sync branch" >&2; exit 5; }
  [[ "$BASE_SHA" =~ ^[0-9a-f]{40}$ && "$VENDOR_COMMIT" =~ ^[0-9a-f]{40}$ ]] || {
    echo "error: invalid sync state commit" >&2; exit 5;
  }
}

push_candidate() {
  git push --atomic "$PRIVATE_REMOTE" \
    "$VENDOR_BRANCH:refs/heads/$VENDOR_BRANCH" \
    "refs/tags/vendor/$SYNC_TAG:refs/tags/vendor/$SYNC_TAG" \
    "$SYNC_BRANCH:refs/heads/$SYNC_BRANCH"
}

finish_integration() {
  local current
  current="$(git branch --show-current)"
  [ "$current" = "$SYNC_BRANCH" ] || {
    echo "error: expected to be on $SYNC_BRANCH, found ${current:-detached HEAD}" >&2
    exit 6
  }
  if [ -n "$(git ls-files -u)" ]; then
    write_summary conflict "$SYNC_TAG" "$SYNC_BRANCH" "unresolved files remain"
    exit 7
  fi

  run_checks
  git add -A
  if git diff --cached --quiet && [ "$(git rev-parse HEAD)" = "$BASE_SHA" ]; then
    git "${GIT_IDENTITY[@]}" commit --allow-empty -m "chore(sync): import $SYNC_TAG into main" \
      -m "Vendor snapshot: $VENDOR_COMMIT"
  elif ! git diff --cached --quiet; then
    git "${GIT_IDENTITY[@]}" commit -m "chore(sync): import $SYNC_TAG into main" \
      -m "Vendor snapshot: $VENDOR_COMMIT"
  fi

  if [ "$MERGE_MAIN" -eq 0 ]; then
    if [ "$PUSH" -eq 1 ]; then push_candidate; fi
    rm -f "$STATE_FILE"
    write_summary candidate "$SYNC_TAG" "$SYNC_BRANCH" "validated candidate ready; main unchanged"
    return
  fi

  [ "$(git rev-parse "$BASE_BRANCH")" = "$BASE_SHA" ] || {
    write_summary blocked "$SYNC_TAG" "$SYNC_BRANCH" "$BASE_BRANCH moved during validation"
    exit 8
  }
  if [ "$PUSH" -eq 1 ]; then
    git fetch --no-tags "$PRIVATE_REMOTE" "refs/heads/$BASE_BRANCH:refs/remotes/$PRIVATE_REMOTE/$BASE_BRANCH"
    [ "$(git rev-parse "refs/remotes/$PRIVATE_REMOTE/$BASE_BRANCH")" = "$BASE_SHA" ] || {
      write_summary blocked "$SYNC_TAG" "$SYNC_BRANCH" "remote $BASE_BRANCH moved during validation"
      exit 8
    }
  fi

  local integration_sha compat_source release_tag increment compat_ref=()
  integration_sha="$(git rev-parse HEAD)"
  git branch -f "$BASE_BRANCH" "$integration_sha"
  compat_source="refs/heads/$COMPAT_BRANCH"
  if [ "$PUSH" -eq 1 ]; then
    git fetch --no-tags "$PRIVATE_REMOTE" "refs/heads/$COMPAT_BRANCH:refs/remotes/$PRIVATE_REMOTE/$COMPAT_BRANCH"
    compat_source="refs/remotes/$PRIVATE_REMOTE/$COMPAT_BRANCH"
  fi
  if git show-ref --verify --quiet "$compat_source" && git merge-base --is-ancestor "$compat_source" "$integration_sha"; then
    # Push the validated SHA; an outdated local compatibility branch is irrelevant.
    compat_ref=("$integration_sha:refs/heads/$COMPAT_BRANCH")
    if [ "$PUSH" -eq 0 ]; then git branch -f "$COMPAT_BRANCH" "$integration_sha"; fi
  fi
  # Public snapshots and local product releases are separate namespaces. A
  # localized release stays on the upstream version line: the plain upstream
  # version while it is still free, otherwise the next unused X.Y.Z.N local
  # increment. Never consume a later upstream patch number — that would make
  # the real upstream release unpublishable and would strand installed clients
  # on a version the genuine release can no longer supersede.
  release_tag="$SYNC_TAG"
  increment=0
  while git show-ref --verify --quiet "refs/tags/$release_tag" ||
        git show-ref --verify --quiet "refs/tags/deploy/$release_tag"; do
    increment=$((increment + 1))
    if [ "$increment" -gt 99 ]; then
      write_summary blocked "$SYNC_TAG" "$SYNC_BRANCH" \
        "no free localized version left for $SYNC_TAG"
      exit 9
    fi
    release_tag="$SYNC_TAG.$increment"
  done
  git "${GIT_IDENTITY[@]}" tag -a "deploy/$release_tag" "$integration_sha" \
    -m "Ubuntu deployment candidate for localized Multica $release_tag (upstream $SYNC_TAG)"
  if [ "$PUSH" -eq 1 ]; then
    git push --atomic "$PRIVATE_REMOTE" \
      "$VENDOR_BRANCH:refs/heads/$VENDOR_BRANCH" \
      "$SYNC_BRANCH:refs/heads/$SYNC_BRANCH" \
      "$BASE_BRANCH:refs/heads/$BASE_BRANCH" \
      "${compat_ref[@]}" \
      "refs/tags/vendor/$SYNC_TAG:refs/tags/vendor/$SYNC_TAG" \
      "refs/tags/deploy/$release_tag:refs/tags/deploy/$release_tag"
  fi
  rm -f "$STATE_FILE"
  write_summary integrated "$SYNC_TAG" "$SYNC_BRANCH" \
    "validated and advanced $BASE_BRANCH as $release_tag; deploy Ubuntu before desktop promotion"
}

if [ "$MODE" = resume ]; then
  load_state
  finish_integration
  exit 0
fi

require_clean_tree

echo "==> Detecting stable public Multica releases"
remote_tags="$(git ls-remote --tags --refs "$PUBLIC_URL" 'v*' | sed 's#.*refs/tags/##')"
if [ -n "$REQUESTED_TAG" ]; then
  is_stable_tag "$REQUESTED_TAG" || { echo "error: --tag requires vX.Y.Z" >&2; exit 2; }
  grep -Fxq "$REQUESTED_TAG" <<<"$remote_tags" || {
    echo "error: public tag $REQUESTED_TAG does not exist" >&2; exit 9;
  }
  SYNC_TAG=$REQUESTED_TAG
else
  SYNC_TAG="$(latest_stable_from_lines <<<"$remote_tags")"
fi
[ -n "$SYNC_TAG" ] || { echo "error: no stable public release tags found" >&2; exit 9; }

vendor_tags="$(git tag --list 'vendor/v*' | sed 's#^vendor/##')"
latest_vendor="$(latest_stable_from_lines <<<"$vendor_tags")"
if [ -n "$latest_vendor" ] && [[ "$(version_key "$SYNC_TAG")" < "$(version_key "$latest_vendor")" ]]; then
  echo "error: refusing to downgrade from $latest_vendor to $SYNC_TAG" >&2
  exit 9
fi
snapshot_exists=0
OLD_VENDOR_TAG="$(integrated_vendor_tag)" || {
  echo "error: integrated vendor trailer cannot be resolved to a vendor tag; refusing to guess a merge base" >&2
  exit 9
}
if git show-ref --verify --quiet "refs/tags/vendor/$SYNC_TAG"; then
  snapshot_exists=1
fi
if [ "$snapshot_exists" -eq 1 ] && [ "$OLD_VENDOR_TAG" = "vendor/$SYNC_TAG" ]; then
  write_summary up-to-date "$SYNC_TAG" "" "pristine snapshot already exists"
  exit 0
fi
if [ "$MODE" = check ]; then
  write_summary available "$SYNC_TAG" "" "new stable public release available"
  exit 10
fi
[ -n "$latest_vendor" ] || { echo "error: no existing vendor/vX.Y.Z baseline" >&2; exit 9; }

[ -n "$OLD_VENDOR_TAG" ] && git show-ref --verify --quiet "refs/tags/$OLD_VENDOR_TAG" || {
  echo "error: cannot determine the vendor snapshot integrated by $BASE_BRANCH" >&2
  exit 9
}
SYNC_BRANCH="sync/upstream-$SYNC_TAG"
git show-ref --verify --quiet "refs/heads/$BASE_BRANCH" || {
  echo "error: missing localized branch $BASE_BRANCH" >&2; exit 9;
}
git show-ref --verify --quiet "refs/heads/$VENDOR_BRANCH" || {
  echo "error: missing pristine branch $VENDOR_BRANCH" >&2; exit 9;
}
if git show-ref --verify --quiet "refs/heads/$SYNC_BRANCH"; then
  echo "error: $SYNC_BRANCH already exists; inspect it or use --resume" >&2
  exit 9
fi
BASE_SHA="$(git rev-parse "$BASE_BRANCH")"

if [ "$snapshot_exists" -eq 0 ]; then
  echo "==> Fetching pristine public snapshot $SYNC_TAG"
  git fetch --no-tags "$PUBLIC_URL" \
    "refs/tags/$SYNC_TAG:refs/upstream-snapshots/$SYNC_TAG"
  git switch "$VENDOR_BRANCH"
  git read-tree --reset -u "refs/upstream-snapshots/$SYNC_TAG^{}"
  git "${GIT_IDENTITY[@]}" commit --allow-empty -m "chore(sync): import upstream $SYNC_TAG"
  VENDOR_COMMIT="$(git rev-parse HEAD)"
  git "${GIT_IDENTITY[@]}" tag -a "vendor/$SYNC_TAG" \
    -m "Pristine Multica upstream snapshot $SYNC_TAG"
  git diff --exit-code "vendor/$SYNC_TAG^{tree}" "refs/upstream-snapshots/$SYNC_TAG^{tree}"
else
  echo "==> Reusing pristine public snapshot $SYNC_TAG"
  VENDOR_COMMIT="$(git rev-parse "vendor/$SYNC_TAG^{commit}")"
fi

echo "==> Applying public delta $OLD_VENDOR_TAG..vendor/$SYNC_TAG"
git switch -c "$SYNC_BRANCH" "$BASE_BRANCH"
save_state
git read-tree -m -u "$OLD_VENDOR_TAG" "$BASE_BRANCH" "vendor/$SYNC_TAG"
if [ -n "$(git ls-files -u)" ]; then
  git checkout --conflict=merge -- . 2>/dev/null || true
  if [ "$PUSH" -eq 1 ]; then
    git push --atomic "$PRIVATE_REMOTE" \
      "$VENDOR_BRANCH:refs/heads/$VENDOR_BRANCH" \
      "refs/tags/vendor/$SYNC_TAG:refs/tags/vendor/$SYNC_TAG" || true
  fi
  conflicts="$(git diff --name-only --diff-filter=U | paste -sd, -)"
  write_summary conflict "$SYNC_TAG" "$SYNC_BRANCH" \
    "resolve conflicts ($conflicts), preserve local boundaries, then run this script --resume"
  exit 7
fi

finish_integration
